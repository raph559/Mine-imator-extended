w(`/// bridge_differs(a, b)
/// @arg a
/// @arg b
/// @desc Whether two numbers differ by more than the 3 decimals the bridge speaks in.

function bridge_differs(a, b)
{
	return (abs(a - b) > 0.0001)
}

/// bridge_number_text_ok(text)
/// @arg text
/// @desc Whether the text is a plain number: digits, an optional leading minus and at most one decimal point.

function bridge_number_text_ok(text)
{
	var digits, dots, c;
	if (text = "")
		return false

	digits = 0
	dots = 0
	for (var i = 1; i <= string_length(text); i++)
	{
		c = string_char_at(text, i)
		if (c = "-" && i = 1)
			continue
		if (c = "." && dots = 0)
		{
			dots++
			continue
		}
		if (ord(c) >= ord("0") && ord(c) <= ord("9"))
		{
			digits++
			continue
		}
		return false
	}

	return (digits > 0)
}

/// bridge_range_error(value, name)
/// @arg value
/// @arg name
/// @desc Returns "" if the value is a number or a "min..max" text with min not above max, otherwise why not.

function bridge_range_error(val, name)
{
	var p, a, b, msg;
	msg = string(name) + " must be a number, or a text like min..max for a random value"
	if (is_real(val))
		return (is_bool(val) ? msg : "")
	if (!is_string(val))
		return msg

	p = string_pos("..", val)
	if (p = 0)
		return msg

	a = string_copy(val, 1, p - 1)
	b = string_copy(val, p + 2, string_length(val) - p - 1)
	if (!bridge_number_text_ok(a) || !bridge_number_text_ok(b))
		return msg
	if (real(a) > real(b))
		return string(name) + ": min must not be above max"

	return ""
}

/// bridge_range_min(text)
/// @arg text

function bridge_range_min(text)
{
	return real(string_copy(text, 1, string_pos("..", text) - 1))
}

/// bridge_range_max(text)
/// @arg text

function bridge_range_max(text)
{
	return real(string_copy(text, string_pos("..", text) + 2, string_length(text)))
}

/// bridge_range_text(min, max)
/// @arg min
/// @arg max

function bridge_range_text(mn, mx)
{
	return string_decimals(bridge_real(mn)) + ".." + string_decimals(bridge_real(mx))
}

/// bridge_color_range_error(value, name)
/// @arg value
/// @arg name
/// @desc Returns "" if the value is a colour "#RRGGBB" or two of them as "#RRGGBB..#RRGGBB", otherwise why not.

function bridge_color_range_error(val, name)
{
	var msg = string(name) + " must be a colour like #RRGGBB, or #RRGGBB..#RRGGBB for a random colour between two";
	if (!is_string(val))
		return msg
	if (string_length(val) = 7)
		return (bridge_is_hex_color(val) ? "" : msg)
	if (string_length(val) = 16 && string_copy(val, 8, 2) = ".." && bridge_is_hex_color(string_copy(val, 1, 7)) && bridge_is_hex_color(string_copy(val, 10, 7)))
		return ""

	return msg
}

/// bridge_ptype_kind_target(id)
/// @arg id
/// @desc The library template that an object id (or a template id) stands for as a particle kind.
/// null if there is no such object, 0 if it cannot be used as a particle.

function bridge_ptype_kind_target(saveid)
{
	var obj = save_id_find(string(saveid));
	if (obj = null || !instance_exists(obj))
		return null

	if (obj.object_index = obj_timeline)
	{
		if (obj.part_of != null)
			obj = obj.part_of
		obj = obj.temp
		if (obj = null || !instance_exists(obj))
			return 0
	}

	if (obj.object_index != obj_template || obj.type = e_temp_type.PARTICLE_SPAWNER)
		return 0

	return obj
}

/// bridge_ptype_kind_name(kindtemp)
/// @arg kindtemp
/// @desc How a particle type's kind reads over the bridge: sprite, sheet, or the id of the object it uses.

function bridge_ptype_kind_name(kindtemp)
{
	if (kindtemp = particle_template)
		return "sprite"
	if (kindtemp = particle_sheet)
		return "sheet"
	if (kindtemp = null || !instance_exists(kindtemp))
		return "sprite"

	// The object that uses this template, or else the template itself
	with (obj_timeline)
		if (part_of = null && temp = kindtemp)
			return save_id

	return kindtemp.save_id
}

/// bridge_ptype_names()
/// @desc Every particle type setting the bridge exposes, in the order they are applied.

function bridge_ptype_names()
{
	return array(${names.map((n) => JSON.stringify(n)).join(", ")})
}
`);

w(`/// bridge_ptype_kind(name)
/// @arg name
/// @desc "text", "spawnrate", "onend", "sprite", "range", "vector", "color", "bool" or "number" for a setting, "" if the name is not one.

function bridge_ptype_kind(name)
{
	switch (name)
	{
		case "name": return "text"
		case "text": return "longtext"
		case "spawn_rate": return "spawnrate"
		case "kind": return "kind"
		case "sprite_template": return "sprite"
		case "sprite_sheet": return "sheet"
		case "sprite_sheet_image": return "sheetimage"
		case "sprite_animation_onend": return "onend"
${scalars.map((s) => `		case "${s[0]}": return "range"`).join("\n")}
${vectors.map((v) => `		case "${v}": return "vector"`).join("\n")}
${colors.map((c) => `		case "${c.name}": return "color"`).join("\n")}
${bools.map((b) => `		case "${b[0]}": return "bool"`).join("\n")}
${numbers.map((n) => `		case "${n[0]}": return "number"`).join("\n")}
	}

	return ""
}
`);

// Reading
w(`/// bridge_ptype_map(ptype)
/// @arg ptype
/// @desc Returns a map of a particle type: its id and every setting. A random value is the text "min..max".

function bridge_ptype_map(p)
{
	var m, list;
	m = ds_map_create()
	m[?"id"] = p.save_id
	m[?"name"] = p.name
	m[?"spawn_rate"] = bridge_real(p.spawn_rate * 100)
	m[?"sprite_template"] = p.sprite_template
	m[?"kind"] = bridge_ptype_kind_name(p.temp)
	m[?"sprite_sheet"] = (p.sprite_tex = mc_res ? "default" : p.sprite_tex.save_id)
	m[?"sprite_sheet_image"] = p.sprite_tex_image
	m[?"text"] = p.text
	if (p.sprite_animation_onend = 1)
		m[?"sprite_animation_onend"] = "loop"
	else if (p.sprite_animation_onend = 2)
		m[?"sprite_animation_onend"] = "reverse"
	else
		m[?"sprite_animation_onend"] = "stop"
`);
for (const [f] of scalars) {
  w(`	if (p.${f}_israndom > 0)
		m[?"${f}"] = bridge_range_text(p.${f}_random_min, p.${f}_random_max)
	else
		m[?"${f}"] = bridge_real(p.${f})
`);
}
for (const f of vectors) {
  w(`	list = ds_list_create()
	for (var a = X; a <= Z; a++)
	{
		if (p.${f}_israndom[a] > 0)
			ds_list_add(list, bridge_range_text(p.${f}_random_min[a], p.${f}_random_max[a]))
		else
			ds_list_add(list, bridge_real(p.${f}[a]))
	}
	ds_map_add_list(m, "${f}", list)
`);
}
for (const c of colors) {
  w(`	if (p.${c.israndom} > 0)
		m[?"${c.name}"] = "#" + color_to_hex(p.${c.from}) + ".." + "#" + color_to_hex(p.${c.to})
	else
		m[?"${c.name}"] = "#" + color_to_hex(p.${c.name})
`);
}
for (const [n, f] of bools) w(`	m[?"${n}"] = (p.${f} > 0)`);
for (const [n, f] of numbers) w(`	m[?"${n}"] = bridge_real(p.${f})`);
w(`
	return m
}
`);

// Checking
w(`/// bridge_ptype_error(name, value)
/// @arg name
/// @arg value
/// @arg settings
/// @desc Returns "" if the particle type setting can be applied with this value, otherwise why not.
/// settings is the decoded request object that holds the value, to tell a list from a number.
/// A message starting with "Unknown sprite" means the sprite template was not found.

function bridge_ptype_error(name, val, settings)
{
	var err;
	if (bridge_ptype_kind(name) != "vector" && bridge_map_item_type(settings, name) != 0)
		return string(name) + " has the wrong kind of value"

	switch (bridge_ptype_kind(name))
	{
		case "text":
			if (!is_string(val) || val = "" || string_length(val) > 100)
				return "name must be a text of 1 to 100 characters"
			return ""

		case "longtext":
			if (!is_string(val) || string_length(val) > 1000)
				return "text must be a text of up to 1000 characters"
			return ""

		case "kind":
		{
			if (!is_string(val) || val = "")
				return "kind must be sprite, sheet, or the id of an object to use as the particle"
			if (val = "sprite" || val = "sheet")
				return ""
			var target = bridge_ptype_kind_target(val);
			if (target = null)
				return "Unknown object " + string(val) + " for kind"
			if (target = 0)
				return "That object cannot be used as a particle (cameras, lights, folders and particle spawners cannot)"
			return ""
		}

		case "sheet":
		{
			if (!is_string(val) || val = "")
				return "sprite_sheet must be default, or the id of an image added with import_image as particle_sheet"
			if (val = "default")
				return ""
			var sheet = bridge_find_res(val);
			if (sheet = null)
				return "Unknown resource " + string(val) + " for sprite_sheet, see list_resources"
			if (sheet.type != e_res_type.PARTICLE_SHEET && sheet.type != e_res_type.PACK)
				return "sprite_sheet must be an image added with import_image as particle_sheet, or a pack"
			return ""
		}

		case "sheetimage":
			if (!is_real(val) || is_bool(val) || (val != 0 && val != 1))
				return "sprite_sheet_image must be 0 or 1 (which of a pack's two particle sheets)"
			return ""

		case "spawnrate":
			if (!is_real(val) || is_bool(val) || val < 0 || val > 100)
				return "spawn_rate must be a percentage from 0 to 100"
			return ""

		case "sprite":
		{
			if (!is_string(val))
				return "sprite_template must be a sprite name, see list_names kind particle_sprites"
			for (var i = 0; i < ds_list_size(particle_template_list); i++)
				if (particle_template_list[|i].name = val)
					return ""
			return "Unknown sprite " + string(val) + ", see list_names kind particle_sprites"
		}

		case "onend":
			if (!is_string(val) || (val != "stop" && val != "loop" && val != "reverse"))
				return "sprite_animation_onend must be stop, loop or reverse"
			return ""

		case "range":
			return bridge_range_error(val, name)

		case "vector":
		{
			if (bridge_map_item_type(settings, name) != ds_type_list || ds_list_size(val) != 3)
				return string(name) + " must be a list of three values [x, y, z], each a number, a min..max text or null"
			for (var a = 0; a < 3; a++)
			{
				if (bridge_list_item_type(val, a) != 0)
					return string(name) + " must be a list of three values [x, y, z], each a number, a min..max text or null"
				if (is_real(val[|a]) && !is_bool(val[|a]) && val[|a] = null)
					continue
				err = bridge_range_error(val[|a], name)
				if (err != "")
					return err
			}
			return ""
		}

		case "color":
			return bridge_color_range_error(val, name)

		case "bool":
			if (!is_bool(val))
				return string(name) + " must be true or false"
			return ""

		case "number":
			return bridge_number_error(name, val)
	}

	return "Unknown particle type setting " + string(name)
}
`);

// Applying
w(`/// bridge_ptype_apply(ptype, name, value)
/// @arg ptype
/// @arg name
/// @arg value
/// @desc Applies one checked setting through the app's actions. The particle spawner template must be temp_edit.
/// The changes are undo steps of their own: a count of the steps is up to the caller.

function bridge_ptype_apply(p, name, val)
{
	var num, mn, mx, item, from, to;
	ptype_edit = p

	switch (name)
	{
		case "name":
			if (p.name != val)
				action_lib_pc_type_name(string(val))
			break

		case "text":
			if (p.text != val)
				action_lib_pc_type_text(string(val))
			break

		case "kind":
		{
			var target;
			if (val = "sprite")
				target = particle_template
			else if (val = "sheet")
				target = particle_sheet
			else
				target = bridge_ptype_kind_target(val)
			if (p.temp != target)
				action_lib_pc_type_temp(target)
			break
		}

		case "sprite_sheet":
		{
			var sheet = mc_res;
			if (val != "default")
				sheet = bridge_find_res(val)
			if (p.sprite_tex != sheet)
				action_lib_pc_type_sprite_tex(sheet)
			break
		}

		case "sprite_sheet_image":
			if (p.sprite_tex_image != round(val))
				action_lib_pc_type_sprite_tex_image(round(val))
			break

		case "spawn_rate":
			num = bridge_real(val)
			if (bridge_differs(p.spawn_rate * 100, num))
				action_lib_pc_type_spawn_rate(num, 0)
			break

		case "sprite_template":
			if (p.sprite_template != val)
				action_lib_pc_type_sprite_template(string(val))
			break

		case "sprite_animation_onend":
		{
			num = 0
			if (val = "loop")
				num = 1
			else if (val = "reverse")
				num = 2
			if (p.sprite_animation_onend != num)
				action_lib_pc_type_sprite_animation_onend(num)
			break
		}
`);
for (const [f, s] of scalars) {
  w(`		case "${f}":
		{
			if (is_string(val))
			{
				mn = bridge_range_min(val)
				mx = bridge_range_max(val)
				if (!(p.${f}_israndom > 0))
					action_lib_pc_type_${f}_israndom(true)
				if (bridge_differs(p.${f}_random_min, mn))
					action_lib_pc_type_${f}_random_min(mn * ${s}, 0)
				if (bridge_differs(p.${f}_random_max, mx))
					action_lib_pc_type_${f}_random_max(mx * ${s}, 0)
			}
			else
			{
				num = bridge_real(val)
				if (p.${f}_israndom > 0)
					action_lib_pc_type_${f}_israndom(false)
				if (bridge_differs(p.${f}, num))
					action_lib_pc_type_${f}(num * ${s}, 0)
			}
			break
		}
`);
}
for (const f of vectors) {
  w(`		case "${f}":
		{
			for (var a = X; a <= Z; a++)
			{
				item = val[|a]
				if (is_real(item) && !is_bool(item) && item = null)
					continue
				axis_edit = a
				if (is_string(item))
				{
					mn = bridge_range_min(item)
					mx = bridge_range_max(item)
					if (!(p.${f}_israndom[a] > 0))
						action_lib_pc_type_${f}_israndom(true)
					if (bridge_differs(p.${f}_random_min[a], mn))
						action_lib_pc_type_${f}_random_min(mn, 0)
					if (bridge_differs(p.${f}_random_max[a], mx))
						action_lib_pc_type_${f}_random_max(mx, 0)
				}
				else
				{
					num = bridge_real(item)
					if (p.${f}_israndom[a] > 0)
						action_lib_pc_type_${f}_israndom(false)
					if (bridge_differs(p.${f}[a], num))
						action_lib_pc_type_${f}(num, 0)
				}
			}
			break
		}
`);
}
for (const c of colors) {
  w(`		case "${c.name}":
		{
			if (string_length(val) > 7)
			{
				from = hex_to_color(string_copy(val, 1, 7))
				to = hex_to_color(string_copy(val, 10, 7))
				if (!(p.${c.israndom} > 0))
					action_lib_pc_type_${c.israndom}(true)
				if (p.${c.from} != from)
					action_lib_pc_type_${c.from}(from)
				if (p.${c.to} != to)
					action_lib_pc_type_${c.to}(to)
			}
			else
			{
				from = hex_to_color(string(val))
				if (p.${c.israndom} > 0)
					action_lib_pc_type_${c.israndom}(false)
				if (p.${c.name} != from)
					action_lib_pc_type_${c.name}(from)
			}
			break
		}
`);
}
for (const [n, f, a] of bools) {
  w(`		case "${n}":
			if ((p.${f} > 0) != (val > 0))
				action_lib_pc_type_${a}((val > 0))
			break
`);
}
for (const [n, f, whole] of numbers) {
  w(`		case "${n}":
			num = ${whole ? "round(val)" : "bridge_real(val)"}
			if (bridge_differs(p.${f}, num))
				action_lib_pc_type_${n}(num, 0)
			break
`);
}
w(`	}
}
`);

// Number checks
w(`/// bridge_number_error(name, value)
/// @arg name
/// @arg value
/// @desc Checks the plain number settings of a particle type.

function bridge_number_error(name, val)
{
	if (!is_real(val) || is_bool(val))
		return string(name) + " must be a number"
`);
for (const [n, , whole, min, max] of numbers) {
  w(`	if (name = "${n}")
	{
		if (val < ${min} || val > ${max}${whole ? " || val != round(val)" : ""})
			return "${n} must be ${whole ? "a whole number" : "a number"} from ${min} to ${max}"
		return ""
	}
`);
}
w(`	return ""
}
`);

